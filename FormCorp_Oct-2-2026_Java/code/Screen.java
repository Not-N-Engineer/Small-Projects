    /*
     * This is a helper method that creates a single line of the screen using a pice of text
     */
    public static String createLine(String text) {
        if(text.length() > 78) { text = text.substring(0, 78); } // Cuts off text past 78 characters
        return "| " + String.format("%-78s", text) + " |";
    }
    
    /*
     * This is a helper method that wraps text around multiple lines
     */
    public static ArrayList<String> wrapText(String text, int width) {
        ArrayList<String> lines = new ArrayList<String>();
        String current = "";
        for(String word : text.split(" ")) {
            while(word.length() > width) {
                if(current.isEmpty()) {
                    lines.add(word.substring(0, width));
                    word = word.substring(width);
                }
                else {
                    lines.add(current);
                    current = "";
                }
            }
            
            if(current.isEmpty()) {
                current = word;
            }
            else if(current.length() + 1 + word.length() <= width) {
                current = current + " " + word;
            }
            else {
                lines.add(current);
                current = word;
            }
        }
        lines.add(current);
        
        return lines;
    }
    
