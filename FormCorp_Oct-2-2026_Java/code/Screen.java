    /*
     * This methods allows pausing for an amount of time between screens. 
     */
    public static void pause(int milliseconds) {
        try {
            Thread.sleep(milliseconds);
        } catch (InterruptedException e) {
            Thread.currentThread().interrupt(); // required handling; this almost never happens in a simple program
        }
    }
    
